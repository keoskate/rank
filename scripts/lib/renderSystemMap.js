// scripts/lib/renderSystemMap.js
//
// Renders a system manifest (from server/systemManifest.js) into ONE
// self-contained HTML file — inline CSS, tiny inline JS for tabs/collapse, and
// the manifest inlined as JSON. No CDN, no external assets: it opens anywhere,
// offline. The HTML is fully server-rendered (readable with JS disabled); the
// JS only toggles which tab/section is visible.

function esc(s) {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const fmt = v => {
  if (v == null) return '—';
  if (typeof v === 'boolean') return v ? 'yes' : 'no';
  if (Array.isArray(v)) return v.length ? v.map(esc).join(', ') : '—';
  return esc(v);
};

const pct = v => (v == null || v === '' ? '—' : `${v}%`);

function chip(label, kind = 'neutral') {
  return `<span class="chip ${kind}">${esc(label)}</span>`;
}

function verdictChip(v) {
  const kind =
    v === 'VALIDATED' ? 'pass' : /^FAILED/.test(v) ? 'fail' : 'muted';
  return chip(v, kind);
}

// key/value rows
function kv(rows) {
  return `<dl class="kv">${rows
    .filter(r => r)
    .map(([k, v]) => `<dt>${esc(k)}</dt><dd>${v}</dd>`)
    .join('')}</dl>`;
}

function table(headers, rows) {
  if (!rows.length) return `<p class="muted">none</p>`;
  return `<table><thead><tr>${headers
    .map(h => `<th>${esc(h)}</th>`)
    .join('')}</tr></thead><tbody>${rows
    .map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`)
    .join('')}</tbody></table>`;
}

// A promotion progress row: actual vs threshold, colored by whether it clears.
function gateRow(label, actual, threshold, ok, suffix = '') {
  const a = actual == null ? '—' : actual;
  const fillPct =
    actual == null || !threshold
      ? 0
      : Math.max(0, Math.min(100, (actual / threshold) * 100));
  return `<div class="gaterow ${ok ? 'ok' : 'no'}">
    <span class="gl">${esc(label)}</span>
    <span class="gbar"><span class="gfill" style="width:${fillPct}%"></span></span>
    <span class="gv">${esc(a)}${suffix} / ${esc(threshold)}${suffix} ${ok ? '✓' : '✗'}</span>
  </div>`;
}

