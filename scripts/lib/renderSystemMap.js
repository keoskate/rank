function renderOverview(m) {
  const byTier = {};
  for (const b of m.brokers)
    if (!b.invalid) byTier[b.tier] = (byTier[b.tier] || 0) + 1;
  const tierChips = Object.entries(byTier)
    .map(([t, n]) => chip(`${n} ${t}`, t === 'paper' ? 'gold' : 'muted'))
    .join(' ');
  const verdictChips = Object.entries(m.evals.verdictTally)
    .map(([v, n]) => `${verdictChip(v)}<span class="tally">×${n}</span>`)
    .join(' ');

  const sent = m.signals.semiconductor.live;
  const sentLine = sent.available
    ? `${chip(sent.direction, sent.direction === 'bullish' ? 'pass' : sent.direction === 'bearish' ? 'fail' : 'muted')} conf ${sent.confidence}% → ${esc(sent.recommendedSymbol || '—')} ${sent.canTrade ? '✓ can-trade' : '· hold'}`
    : `<span class="muted">${esc(sent.reason)}</span>`;

  const macro = m.gates.macro.live;

  return `
  <section class="tabpanel" id="tab-overview">
    <div class="grid">
      <div class="card">
        <h3>Snapshot</h3>
        ${kv([
          ['generated', esc(m.meta.generatedAt)],
          ['git', m.meta.gitSha ? chip(m.meta.gitSha, 'muted') : '—'],
          [
            'mode',
            m.meta.live
              ? chip('live readings', 'pass')
              : chip('offline / config-only', 'muted'),
          ],
          ['brokers', m.meta.brokerCount],
        ])}
      </div>
      <div class="card">
        <h3>Broker tiers</h3>
        <p>${tierChips || '—'}</p>
        <h3 style="margin-top:14px">Semiconductor sentiment</h3>
        <p>${sentLine}</p>
        <h3 style="margin-top:14px">Macro gate</h3>
        <p>${macro.state === 'available' ? chip('live', 'pass') + ' ' + esc(macro.reason || '') : chip(macro.state, 'muted') + ' ' + esc(macro.reason || '')}</p>
      </div>
      <div class="card">
        <h3>Backtest verdicts <span class="muted">(${m.evals.totalRuns} runs)</span></h3>
        <p class="chiprow">${verdictChips || '—'}</p>
        <p class="muted small">A strategy is VALIDATED only by clearing all five gates. Most fail — that's the point.</p>
      </div>
    </div>
    <div class="callout warn">
      <strong>Config drift watch.</strong> ${esc(m.exits.driftWarning)}
    </div>
    <p class="muted small">This page is generated by <code>npm run system-map</code>. Every value is read from source (exported constants, .md frontmatter, session state, run artifacts) — re-run to refresh.</p>
  </section>`;
}

function renderBrokers(m) {
  const cards = m.brokers
    .map(b => {
      if (b.invalid) {
        return `<div class="card broker invalid"><h3>${esc(b.file)} ${chip('INVALID', 'fail')}</h3><p class="muted small">${(b.errors || []).map(esc).join('<br>')}</p></div>`;
      }
      const risk = b.risk || {};
      const regime = b.regime || {};
      const macro = b.macro || {};
      const plugins = Object.entries(b.plugins || {})
        .filter(([, v]) => v && Object.keys(v).length)
        .map(([k, v]) => `<code>${esc(k)}</code>: ${esc(JSON.stringify(v))}`)
        .join('<br>');

      // Live block
      let liveBlock = `<p class="muted small">not materialized as a session</p>`;
      if (b.live) {
        const s = b.live.stats;
        liveBlock = kv([
          [
            'status',
            chip(b.live.status, b.live.status === 'running' ? 'pass' : 'muted'),
          ],
          ['trades', `${s.totalTrades} (${s.wins}W / ${s.losses}L)`],
          // stats.winRate is stored as a percent already (e.g. 22.2), not a fraction.
          ['win rate', pct(s.winRate == null ? null : Math.round(s.winRate))],
          ['total P&L', s.totalPnL == null ? '—' : `$${s.totalPnL}`],
          ['max DD', pct(s.maxDrawdown)],
          ['cons. losses', s.consecutiveLosses],
          [
            'sharpe',
            s.sharpe == null
              ? '<span class="muted">n/a (&lt;2 days)</span>'
              : s.sharpe,
          ],
          b.live.positions.length
            ? [
                'positions',
                b.live.positions
                  .map(p => `${esc(p.symbol)}×${esc(p.qty)}`)
                  .join(', '),
              ]
            : null,
        ]);
      }

      // Promotion block — real evaluator output + progress vs PROMOTE thresholds
      let promoBlock = '';
      if (b.promotion) {
        const P = m.promotion.PROMOTE;
        const mt = b.promotion.metrics || {};
        const actionKind =
          b.promotion.action === 'promote'
            ? 'pass'
            : b.promotion.action === 'fire' ||
                b.promotion.action === 'demote' ||
                b.promotion.action === 'defund'
              ? 'fail'
              : 'muted';
        const bars =
          b.tier === 'simulated'
            ? `
          ${gateRow('Sharpe', mt.sharpe, P.minSharpe, mt.sharpe != null && mt.sharpe >= P.minSharpe)}
          ${gateRow('Win rate', mt.winRate == null ? null : Math.round(mt.winRate * 100), Math.round(P.minWinRate * 100), mt.winRate * 100 >= P.minWinRate * 100, '%')}
          ${gateRow('Max DD', mt.maxDD, P.maxDrawdownPct, mt.maxDD <= P.maxDrawdownPct, '%')}
          ${gateRow('Trades', mt.totalTrades, P.minTrades, mt.totalTrades >= P.minTrades)}
          ${gateRow('Days', mt.days, P.minDays, mt.days >= P.minDays)}`
            : `<p class="muted small">paper-tier — evaluated against DEMOTE/FIRE, not promotion bars.</p>`;
        promoBlock = `
        <div class="promo">
          <p>${chip(b.promotion.action, actionKind)} <span class="muted small">${esc(b.promotion.reason)}</span></p>
          ${bars}
          ${b.promotion.edge ? `<p class="small">Edge gate: ${b.promotion.edge.pass ? chip('pass', 'pass') : chip('fail', 'fail')} <span class="muted">${esc(b.promotion.edge.reason)}</span></p>` : ''}
        </div>`;
      }

      const et = b.exitTunables || {};

      return `<div class="card broker">
        <div class="broker-head">
          <h3>${esc(b.name)} <span class="muted small">${esc(b.slug)}</span></h3>
          <div>${chip(b.tier, b.tier === 'paper' ? 'gold' : 'muted')} ${chip(b.strategy, 'neutral')}</div>
        </div>
        <div class="broker-grid">
          <div>
            <h4>Config</h4>
            ${kv([
              ['capital', `$${esc(b.capital)}`],
              ['effective', `$${esc(b.effectiveCapital)}`],
              ['watchlist', fmt(b.watchlist)],
              [
                'risk/trade',
                pct(
                  risk.perTrade == null
                    ? null
                    : (risk.perTrade * 100).toFixed(2)
                ),
              ],
              [
                'max drawdown',
                pct(
                  risk.maxDrawdown == null
                    ? null
                    : (risk.maxDrawdown * 100).toFixed(0)
                ),
              ],
              ['sizing', fmt(risk.sizing)],
              ['kelly frac', fmt(risk.kellyFraction)],
              ['max positions', fmt(risk.maxPositions)],
              ['max pos size', pct(risk.maxPositionSizePercent)],
              [
                'daily-loss rail',
                risk.dailyLossLimit == null
                  ? '<span class="muted">off</span>'
                  : pct((risk.dailyLossLimit * 100).toFixed(1)),
              ],
              [
                'cons-loss rail',
                risk.maxConsecutiveLosses == null
                  ? '<span class="muted">off</span>'
                  : risk.maxConsecutiveLosses,
              ],
              [
                'regime gate',
                regime.enabled
                  ? `${chip('on', 'pass')} ${esc(regime.preferred)} [${(regime.entropyWindows || []).join(',')}]`
                  : chip('off', 'muted'),
              ],
              [
                'macro gate',
                macro.enabled
                  ? `${chip('on', 'pass')} ×${esc(macro.riskOffScalar)}`
                  : chip('off', 'muted'),
              ],
              plugins ? ['plugins', plugins] : null,
            ])}
            <h4 style="margin-top:12px">Exit tunables</h4>
            ${kv([
              ['stop loss', pct(et.stopLossPercent)],
              ['take profit', pct(et.takeProfitPercent)],
              [
                'trailing',
                et.trailingStopPercent
                  ? pct(et.trailingStopPercent)
                  : '<span class="muted">off</span>',
              ],
              ['RSI overbought', fmt(et.rsiOverbought)],
              [
                'EOD exit',
                et.exitBeforeClose === false
                  ? '<span class="muted">off</span>'
                  : `${et.exitBeforeCloseMinutes}min`,
              ],
              ['min profit exit', fmt(et.minProfitForExitPercent)],
              ['dampening', fmt(et.trendDampeningFactor)],
            ])}
          </div>
          <div>
            <h4>Live</h4>
            ${liveBlock}
            <h4 style="margin-top:12px">Promotion status</h4>
            ${promoBlock || '<p class="muted small">—</p>'}
          </div>
        </div>
        <details><summary>persona</summary><pre class="persona">${esc(b.personaExcerpt)}</pre></details>
      </div>`;
    })
    .join('');
  return `<section class="tabpanel hidden" id="tab-brokers">${cards}</section>`;
}

